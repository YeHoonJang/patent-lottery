#!/usr/bin/env python3
"""
Judge-model dependence test — GPT-5.6 Sol re-scoring for rebuttal (Reviewer pYex W3).

Same 5-item legal coherence checklist as scripts/score_coherence_llm.py (Sonnet 4.6).
Different provider (OpenAI, flagship) → judge-model diversity check.

Sampling: stratified by archetype (7 archetypes × ~29 traces = 200 total).
Output: outputs/coherence_scores_gpt56/<case_id>/<examiner_name>.json

Usage:
  python3 scripts/score_coherence_gpt.py --smoke        # 3 traces smoke test
  python3 scripts/score_coherence_gpt.py --n 200        # stratified 200
  python3 scripts/score_coherence_gpt.py --n 1400       # full replication
"""
import os, sys, json, glob, logging, argparse, random
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor, as_completed
from collections import defaultdict, Counter
import openai

REPO = str(Path(__file__).resolve().parents[1])
TRACES_DIR = f"{REPO}/outputs/exp1_full_100/traces"
SONNET_DIR = f"{REPO}/outputs/coherence_scores"
OUT_DIR = Path(f"{REPO}/outputs/coherence_scores_gpt56")
OUT_DIR.mkdir(parents=True, exist_ok=True)

MODEL = "gpt-5.6-sol"
PARALLEL = 1  # 캐시 히트 보장 위해 순차 실행
MAX_TOKENS = 4096  # 추론 모델 여유 (reasoning 토큰 소모 대응)
CACHE_KEY = "coherence_judge_v1"  # 캐시 서버 고정

if not os.environ.get("OPENAI_API_KEY"):
    raise SystemExit("ERROR: OPENAI_API_KEY not set. Run: set -a; source .env; set +a")

client = openai.OpenAI()

# Archetype prefixes (matches scripts/regen_appendix_figures.py)
ARCHETYPE_PREFIX = {
    "veteran_strict": "C1",
    "lenient_advocate": "C2",
    "strict_gatekeeper": "O1",
    "broad_interpreter": "O2",
    "easy_combiner": "O3",
    "senior_examiner": "O4",
    "domain_specialist": "O5",
}

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[
        logging.StreamHandler(),
        logging.FileHandler(f"{REPO}/outputs/coherence_gpt56.log"),
    ]
)
logger = logging.getLogger("coherence_gpt")

# ─── Judge prompt (identical to Sonnet 4.6 for fair comparison) ─────
SYSTEM_PROMPT = """You are an independent legal-coherence evaluator for U.S. patent examination traces.

Your task is to score a single examiner's reasoning trace on a 5-item binary checklist. The trace was generated by an LLM-simulated examiner with specific calibration parameters (strictness, claim breadth, combination threshold, seniority, tech specialization). The trace consists of examiner profile + stage outputs from a multi-stage examination pipeline (§102 novelty, §103 obviousness, §112 written description, office action, final decision).

For each of the 5 items below, assign 1 (pass) or 0 (fail) and write a brief 1-sentence justification grounded in the trace content.

CHECKLIST:

1. Statute-appropriate framework
   PASS: Invokes the recognized legal test for the relevant statute — e.g., Graham/KSR factors for §103, element-by-element anticipation for §102, Alice/Mayo for §101, claim-specification support for §112.
   FAIL: §103 analysis that uses §101-style abstract-idea reasoning instead of obviousness factors; or any stage that reasons under the wrong statute.

2. Evidence-linked reasoning
   PASS: Conclusions reference specific claim language, prior art disclosures, or specification passages.
   FAIL: "This claim is obvious" with no prior art citation or element comparison.

3. Stage consistency
   PASS: Later-stage conclusions do not contradict earlier-stage findings without stated justification.
   FAIL: Finding weak prior art overlap at §102, then asserting strong §103 rejection on the same elements without additional rationale.

4. Dimension-consistent reasoning
   PASS: The examiner's profile dimensions are reflected in the reasoning — e.g., strict examiner (strictness > 0.7) resolves ambiguity toward rejection; easy combiner (combination_threshold < 0.4) accepts weaker motivation to combine; lenient examiner (strictness < 0.4) leans toward grant on ambiguous evidence.
   FAIL: A strict examiner (strictness > 0.85) granting on ambiguous evidence without any stated weighing; or a lenient examiner rejecting strongly without clear evidence.

5. Non-arbitrary final decision
   PASS: Final decision follows from the accumulated stage-level analyses with stated rationale.
   FAIL: Final decision that reverses the direction of all prior-stage conclusions without explanation.

OUTPUT FORMAT (JSON):
{
  "item1": {"score": 0 or 1, "justification": "..."},
  "item2": {"score": 0 or 1, "justification": "..."},
  "item3": {"score": 0 or 1, "justification": "..."},
  "item4": {"score": 0 or 1, "justification": "..."},
  "item5": {"score": 0 or 1, "justification": "..."},
  "total": 0-5,
  "classification": "legally_coherent" (4-5) | "partially_coherent" (2-3) | "weak" (0-1)
}

Be strict but fair. Reasoning that is brief but on-point passes; reasoning that is verbose but misses the legal framework fails."""

OUTPUT_SCHEMA = {
    "type": "object",
    "properties": {
        "item1": {"type": "object", "properties": {"score": {"type": "integer", "enum": [0, 1]}, "justification": {"type": "string"}}, "required": ["score", "justification"], "additionalProperties": False},
        "item2": {"type": "object", "properties": {"score": {"type": "integer", "enum": [0, 1]}, "justification": {"type": "string"}}, "required": ["score", "justification"], "additionalProperties": False},
        "item3": {"type": "object", "properties": {"score": {"type": "integer", "enum": [0, 1]}, "justification": {"type": "string"}}, "required": ["score", "justification"], "additionalProperties": False},
        "item4": {"type": "object", "properties": {"score": {"type": "integer", "enum": [0, 1]}, "justification": {"type": "string"}}, "required": ["score", "justification"], "additionalProperties": False},
        "item5": {"type": "object", "properties": {"score": {"type": "integer", "enum": [0, 1]}, "justification": {"type": "string"}}, "required": ["score", "justification"], "additionalProperties": False},
        "total": {"type": "integer", "enum": [0, 1, 2, 3, 4, 5]},
        "classification": {"type": "string", "enum": ["legally_coherent", "partially_coherent", "weak"]},
    },
    "required": ["item1", "item2", "item3", "item4", "item5", "total", "classification"],
    "additionalProperties": False,
}


def load_trace_summary(examiner_dir: str) -> str | None:
    runs = sorted(glob.glob(f"{examiner_dir}/run_*"))
    if not runs:
        return None
    run_dir = runs[0]
    required = {
        "examiner_profile": "00_examiner_profile.json",
        "novelty": "03_novelty_assessment.json",
        "obviousness": "04_obviousness_analysis.json",
        "office_action": "05_office_action.json",
        "final_decision": "06_final_decision.json",
    }
    parts = {}
    for key, fname in required.items():
        fpath = f"{run_dir}/{fname}"
        if not os.path.exists(fpath):
            return None
        try:
            with open(fpath) as fh:
                parts[key] = json.load(fh)
        except Exception as e:
            logger.error("Failed reading %s: %s", fpath, e)
            return None
    return json.dumps(parts, ensure_ascii=False, indent=2)


def score_trace(case_id: str, examiner_name: str, trace_summary: str) -> dict | None:
    user_prompt = f"Score the following examiner trace (case_id={case_id}, examiner={examiner_name}):\n\n{trace_summary}"
    try:
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
            response_format={
                "type": "json_schema",
                "json_schema": {
                    "name": "coherence_scoring",
                    "schema": OUTPUT_SCHEMA,
                    "strict": True,
                },
            },
            max_completion_tokens=MAX_TOKENS,
            prompt_cache_key=CACHE_KEY,  # 캐시 서버 고정 → 캐시 히트 보장
        )
        text = response.choices[0].message.content
        result = json.loads(text)
        cached = 0
        details = getattr(response.usage, "prompt_tokens_details", None)
        if details is not None:
            cached = getattr(details, "cached_tokens", 0) or 0
        result["_meta"] = {
            "case_id": case_id,
            "examiner": examiner_name,
            "model": MODEL,
            "usage": {
                "prompt_tokens": response.usage.prompt_tokens,
                "completion_tokens": response.usage.completion_tokens,
                "cached_prompt_tokens": cached,
            },
        }
        return result
    except Exception as e:
        logger.error("[%s/%s] scoring failed: %s", case_id, examiner_name, e)
        return None


def score_one(args):
    case_id, examiner_name, examiner_dir, output_path = args
    if output_path.exists():
        return ("skipped", case_id, examiner_name)
    summary = load_trace_summary(examiner_dir)
    if summary is None:
        return ("incomplete", case_id, examiner_name)
    result = score_trace(case_id, examiner_name, summary)
    if result is None:
        return ("failed", case_id, examiner_name)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
    return ("ok", case_id, examiner_name, result["total"], result["_meta"]["usage"])


def build_task_list(n: int, seed: int = 42) -> list:
    """Stratified sample of n traces by archetype, or all if n>=1400."""
    all_tasks = []
    for case_dir in sorted(glob.glob(f"{TRACES_DIR}/*")):
        if not os.path.isdir(case_dir): continue
        case_id = case_dir.split("/")[-1]
        for ex_dir in sorted(glob.glob(f"{case_dir}/*")):
            if not os.path.isdir(ex_dir): continue
            ex_name = ex_dir.split("/")[-1]
            # archetype = prefix before _NNNN
            archetype = "_".join(ex_name.split("_")[:-1])
            all_tasks.append((archetype, case_id, ex_name, ex_dir))

    logger.info("Available traces: %d", len(all_tasks))
    dist = Counter(t[0] for t in all_tasks)
    logger.info("Per-archetype: %s", dict(dist))

    if n >= len(all_tasks):
        selected = all_tasks
    else:
        # Stratified by archetype
        by_arch = defaultdict(list)
        for t in all_tasks:
            by_arch[t[0]].append(t)
        per = n // len(by_arch)
        remainder = n - per * len(by_arch)
        rng = random.Random(seed)
        selected = []
        for i, (arch, traces) in enumerate(sorted(by_arch.items())):
            take = per + (1 if i < remainder else 0)
            rng.shuffle(traces)
            selected.extend(traces[:take])
        logger.info("Sampled %d traces (per archetype ≈ %d)", len(selected), per)

    return [(cid, ex_name, ex_dir, OUT_DIR / cid / f"{ex_name}.json")
            for (arch, cid, ex_name, ex_dir) in selected]


def estimate_cost(usages: list) -> float:
    """GPT-5.6 Sol: $5/M input, $30/M output. Cached: $0.50/M (rough)."""
    total_in = sum(u["prompt_tokens"] for u in usages)
    total_out = sum(u["completion_tokens"] for u in usages)
    total_cached = sum(u["cached_prompt_tokens"] for u in usages)
    uncached_in = total_in - total_cached
    cost = (uncached_in / 1_000_000) * 5.0 + (total_cached / 1_000_000) * 0.50 + (total_out / 1_000_000) * 30.0
    return cost, total_in, total_out, total_cached


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true", help="3 traces smoke test")
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    n = 3 if args.smoke else args.n
    tasks = build_task_list(n, args.seed)
    logger.info("Task count: %d | model=%s | parallel=%d", len(tasks), MODEL, PARALLEL)

    done, skipped, failed, incomplete = 0, 0, 0, 0
    totals, usages = [], []

    with ThreadPoolExecutor(max_workers=PARALLEL) as executor:
        futures = {executor.submit(score_one, t): t for t in tasks}
        for fut in as_completed(futures):
            result = fut.result()
            status = result[0]
            if status == "ok":
                done += 1
                totals.append(result[3])
                usages.append(result[4])
                if done % 25 == 0 or done <= 5:
                    cost, tin, tout, tc = estimate_cost(usages)
                    logger.info("Progress: %d/%d done | mean %.2f/5 | cost so far ~$%.2f (in=%d/cached=%d/out=%d)",
                                done, len(tasks), sum(totals)/len(totals), cost, tin, tc, tout)
            elif status == "skipped": skipped += 1
            elif status == "failed": failed += 1
            elif status == "incomplete": incomplete += 1

    logger.info("=" * 60)
    logger.info("SCORING COMPLETE")
    logger.info("  Done: %d | Skipped: %d | Failed: %d | Incomplete: %d",
                done, skipped, failed, incomplete)
    if totals:
        score_dist = Counter(totals)
        logger.info("  Mean score: %.2f / 5", sum(totals) / len(totals))
        logger.info("  Distribution: %s", dict(sorted(score_dist.items())))
        logger.info("  Pct 4-5: %.1f%%", 100 * sum(1 for t in totals if t >= 4) / len(totals))
    if usages:
        cost, tin, tout, tc = estimate_cost(usages)
        logger.info("  Tokens: input=%d (cached=%d), output=%d", tin, tc, tout)
        logger.info("  Estimated cost: $%.3f (per trace ≈ $%.4f)", cost, cost / max(1, done))
        # Extrapolate
        for scale in [50, 100, 200, 1400]:
            proj = cost * scale / max(1, done)
            logger.info("  Extrapolated for %d traces: $%.2f", scale, proj)


if __name__ == "__main__":
    main()
